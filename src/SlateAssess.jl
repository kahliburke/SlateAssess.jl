"""
    shuffled_key(a::Assessment, key::AnswerKey, seed) -> (order, key′)

Deterministically permute the option order per question, returning the per-question permutation and the
answer key rewritten to match.

Use it to build variant papers from one source: the same `seed` always reproduces the same paper, so a
variant can be regenerated from its seed alone months later when a mark is queried.

`order[qid]` maps a POSITION in the presented paper to the original option, so an author rendering
question prose can reorder their option text with the same permutation.
"""
function shuffled_key(a::Assessment, key::AnswerKey, seed::Integer)
    order = Dict{String,Vector{String}}()
    newkey = Dict{String,String}()
    for (i, q) in enumerate(a.questions)
        rng = Random.MersenneTwister(hash((seed, q)) % typemax(Int32))
        perm = Random.shuffle(rng, a.choices)
        order[q] = perm
        if haskey(key, q)
            # The key names an option LABEL ("c)"); after permuting, the correct answer sits at whatever
            # label now holds the originally-correct content.
            idx = findfirst(==(key[q]), a.choices)
            idx === nothing && throw(ArgumentError(
                "answer key for $q is \"$(key[q])\", which is not one of the assessment's choices"))
            pos = findfirst(==(a.choices[idx]), perm)
            newkey[q] = a.choices[pos]
        end
    end
    return (order, AnswerKey(newkey))
end

end # module
